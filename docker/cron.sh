#!/usr/bin/env bash
# Простейший планировщик ежедневных задач: дайджест, напоминания о платежах
# по кредитам, проведение постоянных расходов и (1-го числа) отправка бэкапа
# в Telegram.
#
# Почему не Celery: одна рассылка в день на бюджетном сервере не стоит
# брокера, воркера и beat. Почему не системный cron: контейнер тогда
# зависел бы от настройки хоста, а так он самодостаточен и переживает
# перезагрузку сервера сам (restart: unless-stopped).
set -euo pipefail

HOUR="${DIGEST_HOUR:-9}"     # час отправки, локальное время контейнера
MINUTE="${DIGEST_MINUTE:-0}"

echo "[cron] задачи ежедневно в $(printf '%02d:%02d' "$HOUR" "$MINUTE") ($(date +%Z))"

# Секунды до ближайшего HOUR:MINUTE — арифметикой, без GNU-синтаксиса `date -d`,
# чтобы скрипт вёл себя одинаково в любом базовом образе.
seconds_until() {
  h=$(date +%H); m=$(date +%M); s=$(date +%S)
  now=$((10#$h * 3600 + 10#$m * 60 + 10#$s))
  target=$(( $1 * 3600 + $2 * 60 ))
  diff=$((target - now))
  [ "$diff" -le 0 ] && diff=$((diff + 86400))
  echo "$diff"
}

while true; do
  sleep_for=$(seconds_until "$HOUR" "$MINUTE")
  echo "[cron] следующая отправка через $((sleep_for / 60)) мин"
  sleep "$sleep_for"

  echo "[cron] $(date '+%F %T') ежедневные задачи"

  # Каждый сбой глушим по отдельности: одна сетевая ошибка не должна
  # ронять планировщик и отменять остальные задачи.
  python manage.py send_digest    || echo "[cron] ОШИБКА дайджеста" >&2
  python manage.py send_reminders || echo "[cron] ОШИБКА напоминаний" >&2

  # Постоянные расходы (бухуслуги, страховка, зарплата). Команда сама решает,
  # наступил ли день проведения, и не даёт задвоить месяц — поэтому её можно
  # звать хоть каждый день.
  python manage.py post_recurring || echo "[cron] ОШИБКА постоянных расходов" >&2

  # Раз в месяц, 1-го числа — копия базы в Telegram. Все бэкапы лежат на
  # том же сервере, что и база: умрёт диск — исчезнут вместе с ней.
  # Копия в переписке хранится вне сервера и достаётся с телефона.
  if [ "$(date +%d)" = "01" ]; then
    python manage.py send_backup  || echo "[cron] ОШИБКА отправки бэкапа" >&2
  fi
done
